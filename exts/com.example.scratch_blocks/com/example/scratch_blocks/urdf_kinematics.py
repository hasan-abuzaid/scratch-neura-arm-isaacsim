    import json
    import sys
    urdf = sys.argv[1]
    info = generate(urdf)
    print(json.dumps(info, indent=2))
    tip = forward_kinematics(urdf, {}, info["end_effector_frame"])[:3, 3]
    print("Tip at all-zero joints (m, URDF root frame):", np.round(tip, 4))